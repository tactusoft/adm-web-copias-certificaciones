package co.gov.sic.copiasycertificaciones.rest;

public class ConceptoRecaudo {

    protected String codigoRentistico;

    protected long codigoConcepto;

    protected long consecutivoRecibo;

    protected long cantidadRecibos;

    protected long unidadesXRecibo;

    protected Double valorUnitario;

    protected Long numeroMulta;

    protected Long anioRadicacion;

    protected Long numeroRadicacion;

    protected String controlRadicacion;

    protected Long consecutivoRadicacion;

    public String getCodigoRentistico() {
        return codigoRentistico;
    }

    public void setCodigoRentistico(String value) {
        this.codigoRentistico = value;
    }

    public long getCodigoConcepto() {
        return codigoConcepto;
    }

    public void setCodigoConcepto(long value) {
        this.codigoConcepto = value;
    }

    public long getConsecutivoRecibo() {
        return consecutivoRecibo;
    }

    public void setConsecutivoRecibo(long value) {
        this.consecutivoRecibo = value;
    }

    public long getCantidadRecibos() {
        return cantidadRecibos;
    }

    public void setCantidadRecibos(long value) {
        this.cantidadRecibos = value;
    }

    public long getUnidadesXRecibo() {
        return unidadesXRecibo;
    }

    public void setUnidadesXRecibo(long value) {
        this.unidadesXRecibo = value;
    }

    public Double getValorUnitario() {
        return valorUnitario;
    }

    public void setValorUnitario(Double value) {
        this.valorUnitario = value;
    }

    public Long getNumeroMulta() {
        return numeroMulta;
    }

    public void setNumeroMulta(Long value) {
        this.numeroMulta = value;
    }

    public Long getAnioRadicacion() {
        return anioRadicacion;
    }

    public void setAnioRadicacion(Long value) {
        this.anioRadicacion = value;
    }

    public Long getNumeroRadicacion() {
        return numeroRadicacion;
    }

    public void setNumeroRadicacion(Long value) {
        this.numeroRadicacion = value;
    }

    public String getControlRadicacion() {
        return controlRadicacion;
    }

    public void setControlRadicacion(String value) {
        this.controlRadicacion = value;
    }

    public Long getConsecutivoRadicacion() {
        return consecutivoRadicacion;
    }

    public void setConsecutivoRadicacion(Long value) {
        this.consecutivoRadicacion = value;
    }
}
